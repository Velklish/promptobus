// Уборка каталогов прежних прогонов живой канарейки.
//
// Каталог прогона канарейка оставляет на диске намеренно: путь печатается, а отчёт
// (`live-canary.md`) и полный вывод живого круга читают уже после прогона. Мести их при этом
// было некому — ни канарейка, ни `doctor` о них не знали, — и каталоги копились: замер
// 2026-09-03 на машине владельца — девять штук по 20 КБ.
//
// Отдельным модулем, а не функцией внутри [live-canary.mjs](live-canary.mjs): тот исполняется
// целиком уже при импорте — поднимает рабочее место, ставит tarball и гоняет живые сессии, —
// и покрыть уборку набором иначе нечем.
import { readdirSync, rmSync, statSync } from 'node:fs';
import path from 'node:path';

/** Префикс каталога прогона. Дом у него один: `live-canary.mjs` зовёт `mkdtempSync` им же. */
export const CANARY_PREFIX = 'promptobus-canary-';

// Сколько прежних прогонов остаётся. Три, а не один: отчёт последнего прогона читают после
// него, а запас нужен на сравнение двух соседних — «на прошлом было зелено, на этом красно»
// смотрят по двум каталогам сразу. Ноль сносил бы отчёт, который ещё открыт у человека.
export const KEEP_RUNS = 3;

// Возрастная отсечка: моложе этого каталог не сносится, сколько бы свежих ни стояло рядом.
// Порогом «три самых свежих» ИДУЩИЙ прогон не защищён — mtime каталога прогона перестаёт
// расти через секунды после старта (`pack`, клон базы и рабочее место заводятся сразу, дальше
// работа идёт во вложенных каталогах, а отчёт пишется в самом конце), поэтому прогон,
// идущий полчаса, по mtime старше трёх успевших закончиться за это время. Час — запас на
// самый долгий живой прогон: круг канарейки длится минуты.
export const MIN_AGE_MS = 60 * 60 * 1000;

/**
 * Снести каталоги прежних прогонов в `dir`, оставив `keep` самых свежих по mtime. Каталог
 * текущего прогона (`current`) не считается и не сносится: его завела эта же команда.
 *
 * Идущий рядом чужой прогон держится не порядком, а возрастной отсечкой: моложе `MIN_AGE_MS`
 * не сносится ничего. Возвращается перечень снесённого — печатает его вызывающий: молчаливая
 * уборка в общем `$TMPDIR` читается как пропажа.
 *
 * `prefix` — чьи каталоги мести. Копится в `$TMPDIR` не одна канарейка: живая
 * проверка driver'а Cursor оставляет там журналы ходов прогона, гейты релиза — свои каталоги
 * прогона, набор — песочницы оборванных прогонов, и беда у всех общая — та самая,
 * ради которой заведён . Общая беда лечится общим кодом, а не четырьмя копиями
 * порогов: разъехавшись, они дали бы четырём уборкам разные правила на одном каталоге.
 *
 * `refused` — сюда складываются каталоги, снести которые не дали (заняты, чужие права).
 * Перечень отдельный, потому что возврат обещает СНЕСЁННОЕ: обещать снос, которого не было,
 * нельзя — перечень читает человек.
 */
export function sweepPreviousRuns(dir, {
  keep = KEEP_RUNS, current = null, now = Date.now(), prefix = CANARY_PREFIX, refused = [],
} = {}) {
  const mine = current ? path.basename(current) : null;
  const runs = [];
  for (const name of listOf(dir)) {
    if (!name.startsWith(prefix) || name === mine) continue;
    try {
      const st = statSync(path.join(dir, name));
      if (st.isDirectory()) runs.push({ name, at: st.mtimeMs });
    } catch { /* исчез между обходом и вопросом — сносить нечего */ }
  }
  runs.sort((a, b) => b.at - a.at);
  const doomed = runs.slice(keep).filter((r) => now - r.at >= MIN_AGE_MS);
  const swept = [];
  for (const r of doomed) {
    // Отказ сноса не роняет обход и не уносит имена уже снесённых соседей: каталог мог быть
    // занят или права на него чужие, а следующий за ним сносится как ни в чём не бывало.
    // Ловится он ПОКАТАЛОЖНО именно поэтому — охрана на весь обход стирала бы перечень,
    // ради которого уборка и отчитывается.
    try {
      rmSync(path.join(dir, r.name), { recursive: true, force: true });
      swept.push(r.name);
    } catch { refused.push(r.name); }
  }
  return swept;
}

/**
 * Строка итога уборки — одним домом на всех вызывающих. Пустой случай обязан назвать ОБА
 * порога: «сверх трёх оставленных не нашлось» врёт, когда сносить нечего по возрасту, а не
 * по счёту. Пороги подставляются из констант, чтобы фраза не разошлась с кодом.
 */
export function sweptLine(what, swept, { keep = KEEP_RUNS } = {}) {
  if (swept.length) return `${what} снесено: ${swept.length} (${swept.join(', ')})`;
  const guards = [
    ...(keep ? [`в пределах ${keep} оставленных`] : []),
    `моложе ${MIN_AGE_MS / 60_000} минут`,
  ];
  return `${what} сносить нечего: всё ${guards.join(' или ')}`;
}

function listOf(dir) {
  try { return readdirSync(dir); } catch { return []; }
}
