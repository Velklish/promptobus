// Значения контракта шины, которые цитируются прозой: в help CLI, справочнике, гайде и
// скилле оркестрации. Здесь их единственный дом.
//
// **Здесь живёт только harness-neutral** (`BL-466`, ADR-034). Уровни effort, режимы прав,
// версии бинаря и список запрещаемых инструментов переехали к driver'у
// ([driver-claude.js](driver-claude.js)): это словарь ОДНОГО harness'а, и у второго driver'а
// он свой — общий дом означал бы, что шина знает значения Claude Code наизусть. Цитаты
// контракта в документации на них стоят прежние: `lint` берёт значение из нового дома, а
// ключи `<!-- contract:… -->` не менялись.
//
// Модуль листовой — своих импортов у него нет, и это условие работы: его читает help
// `agents.js`, а тот собирается до всякой работы — тянуть ради одной строки резолвер
// репозиториев с GitLab-клиентом (через spawn.js) незачем. По той же цене отсюда убраны
// типы сообщений (`BL-406`): их дом в package, и импорт сюда тянул бы за собой store —
// а этот файл через `bushook.js` читает каждый layout рабочего места.
//
// Отсюда же их берёт `lint`, сверяя прозу с кодом: блок в документации, помеченный
// ключом контракта, обязан перечислять ровно эти значения.

// Имя записи шины в конфиге участника. Оно же — имя canonical сервера базы, и совпадение
// не случайно: имя инструментов (`mcp__promptobus__…`) у оркестратора и участника обязано
// быть одним. spawn.js константу реэкспортирует.
export const PROMPTOBUS_SERVER = 'promptobus';

// Набор инструментов сервера шины. Дом значения здесь, а не в `server.js`: перечень
// цитирует `docs/SPEC.md`, и `lint` сверяет цитату с кодом. Сам сервер объявляет их с
// описаниями и схемами входа; что состав не разъехался с этим списком, держит проверка
// живого `tools/list` в `promptobus-mcp.test.mjs`. Ожидания в наборе нет и не будет
// (ADR-031): будильник в задаче один, и это надзиратель.
//
// **Prefix у имён двойной намеренно** (ADR-032, §8): полное имя, которое видит сессия, —
// `mcp__promptobus__promptobus_send`. Клиент неймспейсит имена сам, а короткие `send` и
// `task` в общем наборе сессии сталкиваются с чужими. Цена известна и принята: префикс
// `PostToolUse:mcp__<сервер>__<…> says:` клиент дописывает к КАЖДОЙ строке записи в ленте.
export const PROMPTOBUS_TOOLS = ['promptobus_send', 'promptobus_mailbox', 'promptobus_task'];

// Версии протокола MCP, которые сервер шины действительно обслуживает. Поверхность одна
// на все три (`initialize`, `ping`, `tools/list`, `tools/call` с текстовым результатом)
// и между редакциями не менялась; расхождения (structured result, elicitation,
// sampling) сервер не заявляет. Порядок значим: первое — своя последняя, ею отвечают
// на незнакомую.
export const PROTOCOL_VERSIONS = ['2025-06-18', '2025-03-26', '2024-11-05'];

// Порог возраста уборки журнала задач, в днях. Выведен из замера (~3 МБ в день плотной
// оркестрации) и из того, ради чего журнал хранится: в переписку закончившегося run
// возвращаются днями, а не неделями. Иное — `--older-than`.
export const PRUNE_DEFAULT_DAYS = 14;

// Сколько знаков текста сообщений несёт notification надзирателя (ADR-029). Бюджет на
// ВЕСЬ блок текста, а не порог на сообщение: пакет из пяти коротких иначе давал бы
// notification впятеро больше самого длинного. Число — не предел канала, а политика: канал
// замерен живьём до 16 МБ знак в знак, предел стоит в цене — notification едет в чужой
// контекст и стоит там токенов, а истина всё равно в mailbox'е. Отмерено по живой
// переписке (768 сообщений, 2026-08-30): две тысячи знаков укладывают 46,5% сообщений
// и медианы типов, где быстрый ответ нужен; `result` (медиана 5298) уезжает счётчиком —
// его читают из mailbox'а целиком.
export const KNOCK_TEXT_MAX = 2000;
