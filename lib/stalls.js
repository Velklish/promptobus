// Слова о стопе участника — те, что одни на все harness'ы (ADR-034). «Встал», «ЧИСЛИТСЯ»,
// «ИСЧЕЗ» и «ГЛУХ» описывают состояние, а не инструмент, и потому живут здесь; МАРШРУТ по
// стопу — команда конкретного harness'а — приходит сюда готовой строкой от его driver'а.
//
// Модуль листовой намеренно: строку собирают adapter, когда печатает `promptobus status`
// или отвечает на `promptobus_mailbox`, и журнал надзирателя — одними словами. Живи она у
// driver'а, adapter импортировал бы его напрямую; живи у adapter'а — driver импортировал бы
// adapter. Общий лист снимает обе зависимости, и разъехаться каналам негде: функция одна.

/** Строка о вставшем участнике. `route` — что делать, словами его harness'а. */
export function stallLine(s, route) {
  // «Встал», «числится», «исчез» и «глух» — четыре состояния, и общего слова у них нет:
  // «встал» обещал бы сессию, которая отвиснет, а глухая работает и об этом не знает.
  const what = s.kind === 'stale'
    ? `ЧИСЛИТСЯ, но процесса за ней нет: ${s.reason}`
    : s.kind === 'gone'
      ? `ИСЧЕЗ: ${s.reason}`
      : s.kind === 'wake-taken'
        ? `ГЛУХ: ${s.reason}`
        : `встал: ${s.reason}`;
  return `${s.address} ${what} — сессия ${s.id ?? s.ref}; ${route}`;
}

// «Пока стоп не снят» говорится только там, где стоп и правда снимается: за мёртвой
// записью снимать нечего, и обещать возврат её сообщений нельзя.
export function stallTail(stalled) {
  const forever = stalled.some((s) => s.kind === 'stale' || s.kind === 'gone');
  return `сообщений от них не будет${forever ? '' : ', пока стоп не снят'}: `
    + 'у каждого свой маршрут, он назван в его строке.';
}
